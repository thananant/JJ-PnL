-- 1) คอลัมน์ตั้งค่ารายคนในตาราง employees
ALTER TABLE employees ADD COLUMN IF NOT EXISTS deposit_target  numeric NOT NULL DEFAULT 5000;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS deposit_monthly numeric NOT NULL DEFAULT 500;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS deposit_opening numeric NOT NULL DEFAULT 0;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS deposit_on      boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN employees.deposit_target  IS 'เป้าหมายเงินประกันรวม (บาท)';
COMMENT ON COLUMN employees.deposit_monthly IS 'หักต่อเดือนโดยอัตโนมัติ (บาท)';
COMMENT ON COLUMN employees.deposit_opening IS 'ยอดที่เก็บมาก่อนเริ่มใช้ระบบ — คนเก็บครบแล้วใส่เท่าเป้าหมาย';
COMMENT ON COLUMN employees.deposit_on      IS 'เปิด/ปิดการหักเงินประกันของคนนี้';

-- 2) ตาราง override รายงวด (แก้จำนวนหักเฉพาะงวด / งดหักงวดนั้น)
CREATE TABLE IF NOT EXISTS deposit_entries (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
  period      text NOT NULL,
  amount      numeric NOT NULL DEFAULT 0,
  note        text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, period)
);

-- 3) RLS แบบเดียวกับตารางอื่นของระบบ
ALTER TABLE deposit_entries ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'deposit_entries' AND policyname = 'deposit_entries_all'
  ) THEN
    CREATE POLICY deposit_entries_all ON deposit_entries
      FOR ALL USING (true) WITH CHECK (true);
  END IF;
END
$$;

-- 4) เปิด realtime ให้หน้าเว็บ sync สด
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE deposit_entries;
  EXCEPTION WHEN duplicate_object THEN
    NULL;
  END;
END
$$;

-- ===== JJ-GRANTS: สิทธิ์ Data API ของตารางในไฟล์นี้ (2026-10-21) =====
-- ตั้งแต่ 2026-10-30 Supabase ไม่เปิดสิทธิ์ให้ตารางใหม่เองแล้ว — ไม่มีบล็อกนี้ แอป (คีย์สาธารณะ) จะเจอ permission denied
-- สิทธิ์เท่ากับที่แอปใช้อยู่จริงก่อนหน้านี้ · ตาราง/วิวที่ไม่มีจะข้าม · รันซ้ำได้ · RLS ยังคุมแถวเหมือนเดิม
do $jjg$
declare t text; s text; tb text[] := array['deposit_entries']::text[]; tr text[] := array[]::text[]; vw text[] := array[]::text[];
begin
  foreach t in array tb || tr loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select, insert, update%s on table public.%I to anon, authenticated',
                   case when t = any(tr) then '' else ', delete' end, t);
    execute format('grant all on table public.%I to service_role', t);
    for s in select c.relname from pg_class c join pg_depend d on d.objid = c.oid and d.deptype in ('a','i')
             where c.relkind = 'S' and d.refobjid = ('public.'||quote_ident(t))::regclass loop
      execute format('grant usage, select on sequence public.%I to anon, authenticated, service_role', s);
    end loop;
  end loop;
  foreach t in array vw loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $jjg$;
