-- ---------- งานที่ถึงกำหนดส่งแล้วแต่ยังไม่ได้ส่ง ----------
-- อ่านการตั้งค่าจาก kpi_settings.line_cfg:
--   {"groups":{"JJRD":"C…","JJLP":"C…"}, "daily":true, "period":true,
--    "daily_at":"09:00", "period_at":"09:10", "since":"<ISO timestamp>"}
-- · ไม่มีกลุ่มของสาขาไหน = สาขานั้นไม่ส่ง
-- · "since" = เริ่มส่งตั้งแต่เมื่อไร (แอปใส่ให้ตอนบันทึกครั้งแรก) — กันตอนเพิ่งตั้งค่าแล้วย้อนส่งของเก่าพรวดเดียว
-- · มองย้อนหลัง 3 วัน: ถ้า cron/ฐานข้อมูลหยุดไปช่วงหนึ่ง กลับมาแล้วส่งตามให้
create or replace function public.kpi_line_due(p_now timestamptz default now())
returns table (kind text, branch text, group_id text, period_key text, d_from date, d_to date, due_at timestamptz)
language sql
stable
set search_path = public
as $$
  with cfg as (
    select coalesce((select value from kpi_settings where key = 'line_cfg'), '{}'::jsonb) as v
  ), s as (
    select coalesce((v->>'daily')::boolean, true)                     as daily_on,
           coalesce((v->>'period')::boolean, true)                    as period_on,
           coalesce(nullif(v->>'daily_at', '')::time, time '09:00')   as daily_at,
           coalesce(nullif(v->>'period_at', '')::time, time '09:10')  as period_at,
           coalesce(nullif(v->>'since', '')::timestamptz, p_now - interval '20 hours') as since,
           coalesce(v->'groups', '{}'::jsonb)                         as groups
      from cfg
  ), br as (
    select g.key as branch, btrim(g.value) as group_id
      from s, jsonb_each_text(s.groups) g
     where btrim(coalesce(g.value, '')) <> ''
  ), dt as (
    select d::date as d
      from generate_series((p_now at time zone 'Asia/Bangkok')::date - 3,
                           (p_now at time zone 'Asia/Bangkok')::date,
                           interval '1 day') d
  ), cand as (
    select 'daily'::text as kind, (dt.d - 1) as d_from, (dt.d - 1) as d_to,
           ((dt.d + s.daily_at) at time zone 'Asia/Bangkok') as due_at
      from dt, s where s.daily_on
    union all
    select 'period'::text, date_trunc('month', dt.d)::date, date_trunc('month', dt.d)::date + 14,
           ((dt.d + s.period_at) at time zone 'Asia/Bangkok')
      from dt, s where s.period_on and extract(day from dt.d) = 16
    union all
    select 'period'::text, (date_trunc('month', dt.d) - interval '1 month')::date + 15, date_trunc('month', dt.d)::date - 1,
           ((dt.d + s.period_at) at time zone 'Asia/Bangkok')
      from dt, s where s.period_on and extract(day from dt.d) = 1
  ), k as (
    select c.*, case when c.kind = 'daily' then 'D' || to_char(c.d_to, 'YYYY-MM-DD')
                     else 'P' || to_char(c.d_from, 'YYYY-MM-DD') || '_' || to_char(c.d_to, 'YYYY-MM-DD') end as period_key
      from cand c
  )
  select k.kind, br.branch, br.group_id, k.period_key, k.d_from, k.d_to, k.due_at
    from k cross join br cross join s
   where k.due_at <= p_now
     and k.due_at >= s.since
     and not exists (
       select 1 from kpi_line_log l
        where l.kind = k.kind and l.branch = br.branch and l.period_key = k.period_key
          and (l.ok is not false or l.tries >= 3))
   order by k.due_at, br.branch, k.kind;
$$;

-- ---------- ตัวเดินงาน (cron เรียกทุก 10 นาที) ----------
-- ① เก็บผลการส่งรอบก่อน (pg_net ส่งแบบไม่รอคำตอบ — ผลอยู่ใน net._http_response)
-- ② ส่งงานที่ถึงกำหนด · จองแถวใน kpi_line_log ก่อนยิงเสมอ (ส่งสำเร็จ = ไม่ส่งซ้ำ · ล้มเหลวลองใหม่ได้ 3 ครั้ง)
create or replace function public.kpi_line_tick()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  c_ep   constant text := 'https://aikyxvluaiubdidqxwnd.supabase.co/functions/v1/line-order';
  c_key  constant text := 'sb_publishable_Bn6BMtcjasoPT3RZ_ekyOg_SLWWp-nm';  -- คีย์สาธารณะชุดเดียวกับหน้าแอป
  r       record;
  v_id    bigint;
  v_req   bigint;
  v_txt   text;
  n_sent  int := 0;
  n_check int := 0;
begin
  begin
    update kpi_line_log l
       set ok      = x.good,
           detail  = x.detail,
           sent_at = coalesce(l.sent_at, now())
      from (
        select l2.id,
               (res.status_code between 200 and 299) as good,
               left(coalesce(nullif(res.error_msg, ''),
                             case when res.status_code between 200 and 299 then null
                                  else 'HTTP ' || res.status_code || ' ' || coalesce(res.content, '') end), 300) as detail
          from kpi_line_log l2
          join net._http_response res on res.id = l2.req_id
         where l2.ok is null and l2.req_id is not null
      ) x
     where l.id = x.id;
    get diagnostics n_check = row_count;
  exception when others then
    n_check := -1;    -- pg_net เวอร์ชันต่าง/ผลหมดอายุ — ไม่ให้ล้มทั้งงาน
  end;

  for r in select * from kpi_line_due(now()) loop
    v_id := null;
    insert into kpi_line_log (kind, branch, period_key, d_from, d_to, group_id, tries, sent_at)
    values (r.kind, r.branch, r.period_key, r.d_from, r.d_to, r.group_id, 1, now())
    on conflict (kind, branch, period_key) do update
       set tries    = kpi_line_log.tries + 1,
           ok       = null,
           req_id   = null,
           detail   = null,
           group_id = excluded.group_id,
           sent_at  = now()
     where kpi_line_log.ok is false and kpi_line_log.tries < 3
    returning id into v_id;
    if v_id is null then continue; end if;     -- ส่งสำเร็จแล้ว/ลองครบแล้ว

    v_txt := kpi_line_text(r.branch, r.d_from, r.d_to);
    select net.http_post(
             url     := c_ep,
             body    := jsonb_build_object('to', r.group_id, 'text', v_txt),
             headers := jsonb_build_object('Content-Type', 'application/json',
                                           'apikey', c_key,
                                           'Authorization', 'Bearer ' || c_key),
             timeout_milliseconds := 20000)
      into v_req;
    update kpi_line_log set req_id = v_req where id = v_id;
    n_sent := n_sent + 1;
  end loop;

  return jsonb_build_object('sent', n_sent, 'checked', n_check, 'at', now());
end
$$;

