create table if not exists public.alg_items (
  id          bigint generated by default as identity primary key,
  name        text not null,
  kind        text not null default 'menu',      -- menu อาหาร · meat เนื้อสัตว์/ของสด · sauce น้ำจิ้ม/ซอส · drink เครื่องดื่ม · dessert ของหวาน · product สินค้า · other
  cat         text,                               -- หมวดย่อย (พิมพ์เอง)
  ingredients text,                               -- ส่วนผสม (ค้นหาด้วยคำได้)
  contains    text[] not null default '{}',       -- มีแน่นอน
  may         text[] not null default '{}',       -- อาจปนเปื้อน (ใช้อุปกรณ์/น้ำมันร่วม)
  note        text,
  checked     boolean not null default false,     -- ยืนยันข้อมูลแล้ว (ยังไม่ยืนยัน = แอปไม่บอกว่า "ทานได้")
  checked_by  text,
  checked_at  timestamptz,
  active      boolean not null default true,      -- เลิกขาย = false (ไม่ลบ)
  src         text,                               -- ที่มาตอนนำเข้า เช่น qr:12 / ck:5 (กันนำเข้าซ้ำ)
  sort        int not null default 0,
  created_at  timestamptz not null default now(),
  created_by  text,
  updated_at  timestamptz not null default now(),
  updated_by  text
);
create unique index if not exists alg_items_src_uq on public.alg_items(src) where src is not null;
create index if not exists alg_items_contains_gin on public.alg_items using gin(contains);
create index if not exists alg_items_may_gin on public.alg_items using gin(may);

create table if not exists public.alg_settings (
  key        text primary key,
  value      jsonb,
  updated_at timestamptz not null default now(),
  updated_by text
);

create table if not exists public.alg_log (
  id         bigint generated by default as identity primary key,
  item_id    bigint,
  item_name  text,
  action     text not null,                      -- add · edit · check · off · on · del · import · allergens
  detail     jsonb,
  by_user    text,
  created_at timestamptz not null default now()
);
create index if not exists alg_log_created_idx on public.alg_log(created_at desc);

alter table public.alg_items    enable row level security;
alter table public.alg_settings enable row level security;
alter table public.alg_log      enable row level security;

drop policy if exists alg_items_all on public.alg_items;
create policy alg_items_all on public.alg_items for all using (true) with check (true);
drop policy if exists alg_settings_all on public.alg_settings;
create policy alg_settings_all on public.alg_settings for all using (true) with check (true);
drop policy if exists alg_log_read on public.alg_log;
create policy alg_log_read on public.alg_log for select using (true);
drop policy if exists alg_log_add on public.alg_log;
create policy alg_log_add on public.alg_log for insert with check (true);

grant select, insert, update, delete on public.alg_items, public.alg_settings to anon, authenticated;
grant select, insert on public.alg_log to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

notify pgrst, 'reload schema';

