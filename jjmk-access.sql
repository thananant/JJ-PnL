-- 7) บัญชีพนักงานเดิมที่ยังไม่เคยตั้งสิทธิ์รายแอพ -------------------------------
--    แปลง perms เดิมของระบบ P&L (edit/view/none) มาเป็นแผนสิทธิ์แอพ pnl ให้อัตโนมัติ
--    ระบบอื่นเว้นว่างไว้ = เข้าไม่ได้ จนกว่า admin จะติ๊กเปิดในหน้าจัดการผู้ใช้กลาง
update pnl_users u
set apps = jsonb_build_object('pnl', (
  select coalesce(jsonb_object_agg(k, case when val='edit' then 'vaed' when val='view' then 'v' else '' end), '{}'::jsonb)
  from (select key as k, perms->>key as val from jsonb_object_keys(coalesce(u.perms,'{}'::jsonb)) as key) t
  where val in ('edit','view')
))
where role <> 'admin' and (apps is null or apps = '{}'::jsonb) and perms is not null and perms <> '{}'::jsonb;

