-- 1) รายการยืมเงิน MOU (คนละ 1 รายการ)
CREATE TABLE IF NOT EXISTS mou_loans (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  bigint NOT NULL UNIQUE REFERENCES employees (id) ON DELETE CASCADE,
  amount       numeric NOT NULL DEFAULT 15000,
  monthly      numeric NOT NULL DEFAULT 2000,
  final_max    numeric NOT NULL DEFAULT 3000,
  start_period text NOT NULL DEFAULT '',
  opening      numeric NOT NULL DEFAULT 0,
  doc_passport boolean NOT NULL DEFAULT true,
  doc_pink     boolean NOT NULL DEFAULT true,
  doc_complete boolean NOT NULL DEFAULT false,
  note         text NOT NULL DEFAULT '',
  returned_at  date,
  created_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN mou_loans.amount       IS 'ยอดเงินที่ยืมไปทำ MOU (ปกติ 15000)';
COMMENT ON COLUMN mou_loans.monthly      IS 'หักคืนต่อเดือน (ปกติ 2000)';
COMMENT ON COLUMN mou_loans.final_max    IS 'คงเหลือไม่เกินเท่านี้ หักหมดในงวดสุดท้าย (ปกติ 3000)';
COMMENT ON COLUMN mou_loans.start_period IS 'เริ่มหักตั้งแต่งวด YYYY-MM';
COMMENT ON COLUMN mou_loans.opening      IS 'ยอดที่หักไปก่อนเริ่มใช้ระบบ';
COMMENT ON COLUMN mou_loans.doc_passport IS 'บริษัทเก็บ Passport ไว้';
COMMENT ON COLUMN mou_loans.doc_pink     IS 'บริษัทเก็บบัตรชมพูไว้';
COMMENT ON COLUMN mou_loans.doc_complete IS 'เอกสาร MOU ครบถ้วนแล้ว';
COMMENT ON COLUMN mou_loans.returned_at  IS 'วันที่คืนเอกสารให้พนักงาน (คืนเมื่อหักครบ)';

-- 2) แก้จำนวนหักเฉพาะงวด (override)
CREATE TABLE IF NOT EXISTS mou_entries (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
  period      text NOT NULL,
  amount      numeric NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, period)
);

-- 3) สมุดยืม-คืนเอกสาร
CREATE TABLE IF NOT EXISTS doc_borrows (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
  doc         text NOT NULL,
  borrow_date date NOT NULL DEFAULT CURRENT_DATE,
  return_date date,
  note        text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN doc_borrows.doc         IS 'เอกสารที่ยืม เช่น Passport / บัตรชมพู';
COMMENT ON COLUMN doc_borrows.borrow_date IS 'วันที่ยืมออกไป';
COMMENT ON COLUMN doc_borrows.return_date IS 'วันที่นำมาคืน (ว่าง = ยังไม่คืน)';

-- 4) RLS แบบเดียวกับตารางอื่นของระบบ
ALTER TABLE mou_loans   ENABLE ROW LEVEL SECURITY;
ALTER TABLE mou_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE doc_borrows ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'mou_loans' AND policyname = 'mou_loans_all') THEN
    CREATE POLICY mou_loans_all ON mou_loans FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'mou_entries' AND policyname = 'mou_entries_all') THEN
    CREATE POLICY mou_entries_all ON mou_entries FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'doc_borrows' AND policyname = 'doc_borrows_all') THEN
    CREATE POLICY doc_borrows_all ON doc_borrows FOR ALL USING (true) WITH CHECK (true);
  END IF;
END
$$;

-- 5) เปิด realtime ให้หน้าเว็บ sync สด
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE mou_loans;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE mou_entries;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE doc_borrows;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
END
$$;

-- ===== JJ-GRANTS: สิทธิ์ Data API ของตารางในไฟล์นี้ (2026-10-21) =====
-- ตั้งแต่ 2026-10-30 Supabase ไม่เปิดสิทธิ์ให้ตารางใหม่เองแล้ว — ไม่มีบล็อกนี้ แอป (คีย์สาธารณะ) จะเจอ permission denied
-- สิทธิ์เท่ากับที่แอปใช้อยู่จริงก่อนหน้านี้ · ตาราง/วิวที่ไม่มีจะข้าม · รันซ้ำได้ · RLS ยังคุมแถวเหมือนเดิม
do $jjg$
declare t text; s text; tb text[] := array['mou_loans','mou_entries','doc_borrows']::text[]; tr text[] := array[]::text[]; vw text[] := array[]::text[];
begin
  foreach t in array tb || tr loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select, insert, update%s on table public.%I to anon, authenticated',
                   case when t = any(tr) then '' else ', delete' end, t);
    execute format('grant all on table public.%I to service_role', t);
    for s in select c.relname from pg_class c join pg_depend d on d.objid = c.oid and d.deptype in ('a','i')
             where c.relkind = 'S' and d.refobjid = ('public.'||quote_ident(t))::regclass loop
      execute format('grant usage, select on sequence public.%I to anon, authenticated, service_role', s);
    end loop;
  end loop;
  foreach t in array vw loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $jjg$;
