-- jj_pay_close.sql — 🔒 ปิดงวดเงินเดือน: เก็บสลิปฉบับที่จ่ายแล้วต่อคน·งวด (ห้ามแก้/ลบ · เปิดงวดใหม่ = เพิ่มรุ่นใหม่)
-- รันทั้งไฟล์ใน Supabase SQL Editor (กด Ctrl+A เลือกทั้งหมดก่อน Run) · รันซ้ำได้ ไม่พัง · ไม่แตะตารางเดิม
-- pay_batches = หัวรายการ (สร้างไฟล์ K BIZ / ปิดงวด / เปิดงวดใหม่) · pay_slips = สลิปแช่แข็งต่อคน·งวด·รุ่น
-- สถานะของคน·งวด = แถว pay_slips รุ่นสูงสุด: kind 'close' = ปิดแล้ว · 'reopen' หรือไม่มีแถว = ยังเปิด
-- ปิดงวด = พนักงานที่มีสิทธิ์กดเองหลังโอนเงิน (ไม่มีปิดอัตโนมัติ — เจ้าของสั่ง 2026-10-21)
-- ยังไม่รันไฟล์นี้ = แอปทำงานแบบเดิมทุกอย่าง (ไม่มีปุ่มปิดงวด)
-- ⚠️ ก่อนรัน: ทุกเครื่อง/มือถือที่เปิดแอปเงินเดือน ลากหน้าลงจนเห็นป้ายรุ่นที่มีคำว่า "ปิดงวด v1" (เช่น "2026-10-21 · เงินประกัน v2.3 · เริ่มหักรายคน · ปิดงวด v1") ท้ายเมนู
--    เครื่องรุ่นเก่าไม่รู้จักการปิดงวด: ยังคิดงวดที่ปิดสด · 🔒 อัตโนมัติวันจ่าย · บันทึกเบิก/เพิ่ม-หัก/OT/✎ ลงงวดที่ปิดได้ (ยอดนั้นไม่ถูกนับทั้งในสลิปที่ปิดและงวดถัดไป)
--    ตัวกันฝั่งฐานข้อมูล (jj_pay_close_guard.sql · ขั้น 4) ยังไม่อยู่ในไฟล์นี้ — รันหลังทุกเครื่องเป็นรุ่นใหม่และปิดงวดแรกสำเร็จ
