CREATE TABLE IF NOT EXISTS payroll_audit (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     text NOT NULL DEFAULT '',
  display_name text NOT NULL DEFAULT '',
  action       text NOT NULL DEFAULT '',
  tbl          text NOT NULL DEFAULT '',
  detail       text NOT NULL DEFAULT '',
  page         text NOT NULL DEFAULT '',
  at           timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS payroll_audit_id_idx ON payroll_audit (id DESC);

ALTER TABLE payroll_audit ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS payroll_audit_all ON payroll_audit;

CREATE POLICY payroll_audit_all ON payroll_audit FOR ALL USING (true) WITH CHECK (true);

DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE payroll_audit;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
