-- 1) สมาชิก + วิธีหัก/สมทบ (คนละ 1 แถว)
CREATE TABLE IF NOT EXISTS pvd_members (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  bigint NOT NULL UNIQUE REFERENCES employees (id) ON DELETE RESTRICT,
  emp_mode     text    NOT NULL DEFAULT 'fixed' CHECK (emp_mode IN ('fixed','pct')),
  emp_value    numeric NOT NULL DEFAULT 0 CHECK (emp_value >= 0),
  er_mode      text    NOT NULL DEFAULT 'none' CHECK (er_mode IN ('none','match','fixed','pct')),
  er_value     numeric NOT NULL DEFAULT 0 CHECK (er_value >= 0),
  start_period text    NOT NULL DEFAULT '' CONSTRAINT pvd_members_start_chk CHECK (start_period ~ '^([0-9]{4}-[0-9]{2})?$'),
  stop_period  text    NOT NULL DEFAULT '' CONSTRAINT pvd_members_stop_chk CHECK (stop_period ~ '^([0-9]{4}-[0-9]{2})?$'),
  opening_emp  numeric NOT NULL DEFAULT 0,
  opening_er   numeric NOT NULL DEFAULT 0,
  join_date    date,
  consent      boolean NOT NULL DEFAULT false,
  note         text    NOT NULL DEFAULT '',
  created_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN pvd_members.emp_mode     IS 'พนักงานหัก: fixed = บาทต่องวด · pct = % ของค่าแรงงวดนั้น (p.base)';
COMMENT ON COLUMN pvd_members.er_mode      IS 'ร้านสมทบ: none · match = % ของยอดที่พนักงานหัก (50 = ครึ่งหนึ่ง) · fixed = บาทต่องวด · pct = % ของค่าแรงงวดนั้น';
COMMENT ON COLUMN pvd_members.start_period IS 'เริ่มหักตั้งแต่งวด YYYY-MM';
COMMENT ON COLUMN pvd_members.stop_period  IS 'หยุดหักตั้งแต่งวด YYYY-MM ('''' = ยังหักอยู่) — ใช้แทนการลบ';
COMMENT ON COLUMN pvd_members.opening_emp  IS 'ยอดส่วนพนักงานที่สะสมมาก่อนใช้ระบบ';
COMMENT ON COLUMN pvd_members.opening_er   IS 'ยอดส่วนร้านสมทบที่สะสมมาก่อนใช้ระบบ';
COMMENT ON COLUMN pvd_members.consent      IS 'พนักงานเซ็นหนังสือยินยอมให้หักค่าจ้างแล้ว';
COMMENT ON COLUMN pvd_members.note         IS 'ข้อตกลง/เงื่อนไข (เช่น สิทธิ์ในส่วนร้านสมทบเมื่อถอน/ลาออก)';

-- 2) ยอดรายงวด: แก้เอง (override) หรือปิดยอดงวดที่จ่ายแล้ว
CREATE TABLE IF NOT EXISTS pvd_entries (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE RESTRICT,
  period      text NOT NULL CONSTRAINT pvd_entries_period_chk CHECK (period ~ '^[0-9]{4}-[0-9]{2}$'),
  emp_amount  numeric CHECK (emp_amount >= 0),
  er_amount   numeric CHECK (er_amount >= 0),
  note        text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, period)
);

COMMENT ON COLUMN pvd_entries.emp_amount IS 'ยอดหักพนักงานงวดนี้ — NULL = อัตโนมัติ · 0 = งดหัก';
COMMENT ON COLUMN pvd_entries.er_amount  IS 'ยอดร้านสมทบงวดนี้ — NULL = อัตโนมัติ · 0 = ไม่สมทบ';
COMMENT ON COLUMN pvd_entries.note       IS ''''' = แก้เอง · ''lock'' = ปิดยอดงวดที่จ่ายแล้ว (ทั้งสองช่องมีค่า)';

-- 3) ถอน / จ่ายคืน (รายครั้ง)
CREATE TABLE IF NOT EXISTS pvd_payouts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE RESTRICT,
  pay_date    date NOT NULL DEFAULT CURRENT_DATE,
  period      text NOT NULL CONSTRAINT pvd_payouts_period_chk CHECK (period ~ '^[0-9]{4}-[0-9]{2}$'),
  amount      numeric NOT NULL CHECK (amount > 0),
  via         text NOT NULL DEFAULT 'cash' CHECK (via IN ('slip','cash','transfer')),
  note        text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN pvd_payouts.period IS 'งวดที่ตัดยอด YYYY-MM — via=slip = บวกเข้าสลิปงวดนี้';
COMMENT ON COLUMN pvd_payouts.via    IS 'slip = จ่ายคืนในสลิปเงินเดือน · cash = เงินสด · transfer = โอนนอกสลิป';

CREATE INDEX IF NOT EXISTS pvd_payouts_emp_idx ON pvd_payouts (employee_id, period);

-- 3.1) รันซ้ำบนตารางที่สร้างไว้ก่อนแล้ว: เติม CHECK รูปแบบงวด (กันข้อความแปลกในช่องงวด — แอปใส่ค่าลงหน้าจอ)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pvd_members_start_chk') THEN
    ALTER TABLE pvd_members ADD CONSTRAINT pvd_members_start_chk CHECK (start_period ~ '^([0-9]{4}-[0-9]{2})?$');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pvd_members_stop_chk') THEN
    ALTER TABLE pvd_members ADD CONSTRAINT pvd_members_stop_chk CHECK (stop_period ~ '^([0-9]{4}-[0-9]{2})?$');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pvd_entries_period_chk') THEN
    ALTER TABLE pvd_entries ADD CONSTRAINT pvd_entries_period_chk CHECK (period ~ '^[0-9]{4}-[0-9]{2}$');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pvd_payouts_period_chk') THEN
    ALTER TABLE pvd_payouts ADD CONSTRAINT pvd_payouts_period_chk CHECK (period ~ '^[0-9]{4}-[0-9]{2}$');
  END IF;
END
$$;

-- 4) RLS แบบเดียวกับตารางอื่นของระบบ
ALTER TABLE pvd_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE pvd_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE pvd_payouts ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pvd_members' AND policyname = 'pvd_members_all') THEN
    CREATE POLICY pvd_members_all ON pvd_members FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pvd_entries' AND policyname = 'pvd_entries_all') THEN
    CREATE POLICY pvd_entries_all ON pvd_entries FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pvd_payouts' AND policyname = 'pvd_payouts_all') THEN
    CREATE POLICY pvd_payouts_all ON pvd_payouts FOR ALL USING (true) WITH CHECK (true);
  END IF;
END
$$;

-- 4.1) สิทธิ์อ่าน/เขียนของแอป (โปรเจกต์นี้ตารางใหม่ไม่ได้สิทธิ์อัตโนมัติ — เคยเจอ 'permission denied for table social_mentions' 2026-09-29)
--      ไม่ใส่ = แอปขึ้น "ไม่มีสิทธิ์อ่าน pvd_… — รัน GRANT" และบล็อกสลิป/Excel/K BIZ ทั้งแอปเงินเดือน · รันซ้ำได้
GRANT SELECT, INSERT, UPDATE, DELETE ON pvd_members, pvd_entries, pvd_payouts TO anon, authenticated;

-- 5) เปิด realtime (แอปฟังในช่องแยก jjmk-pvd — ไม่ใช่ jjmk-live)
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE pvd_members;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE pvd_entries;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE pvd_payouts;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
END
$$;
