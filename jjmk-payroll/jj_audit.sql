-- ตารางนี้เก็บว่า "ใคร" เพิ่ม/แก้ไข/ลบ อะไร เมื่อไหร่ ในระบบเงินเดือน
-- รันทั้งไฟล์ใน Supabase SQL Editor (Ctrl+A ก่อน Run) · รันซ้ำได้ ไม่พัง
