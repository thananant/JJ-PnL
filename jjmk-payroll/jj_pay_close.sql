-- 1) หัวรายการ: 1 แถวต่อการกระทำ 1 ครั้ง
CREATE TABLE IF NOT EXISTS pay_batches (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         text NOT NULL CHECK (kind IN ('kbiz', 'close', 'reopen')),
  period       text NOT NULL CONSTRAINT pay_batches_period_chk CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  cycle        text NOT NULL DEFAULT 'store' CHECK (cycle IN ('store', 'office', 'all')),
  branch       text NOT NULL DEFAULT '',                      -- '' = ทุกสาขา · บัญชีที่เห็นบางสาขา (_br) = สาขาที่ปิดจริง เช่น 'JJRD' หรือ 'JJRD,JJCK'
  src          text NOT NULL DEFAULT '' CHECK (src IN ('', 'manual', 'kbiz', 'file', 'calc')),
  reason       text NOT NULL DEFAULT '',
  n            integer NOT NULL DEFAULT 0,
  total        numeric(14,2) NOT NULL DEFAULT 0,
  meta         jsonb NOT NULL DEFAULT '{}'::jsonb,
  app_ver      text NOT NULL DEFAULT '',
  username     text NOT NULL DEFAULT '',
  display_name text NOT NULL DEFAULT '',
  at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pay_batches_reason_chk CHECK (kind <> 'reopen' OR length(btrim(reason)) >= 10)
);
CREATE INDEX IF NOT EXISTS pay_batches_period_idx ON pay_batches (period, kind);

COMMENT ON COLUMN pay_batches.kind   IS 'kbiz = สร้างไฟล์โอนเงินเดือน (เก็บยอดรายคนในไฟล์เป็นหลักฐาน) · close = ปิดงวด · reopen = เปิดงวดใหม่ (เจ้าของ/แอดมิน)';
COMMENT ON COLUMN pay_batches.branch IS 'สาขาที่ทำ ('''' = ทุกสาขาในรอบ)';
COMMENT ON COLUMN pay_batches.reason IS 'เหตุผล — เปิดงวดใหม่ต้องมีอย่างน้อย 10 ตัวอักษร';
COMMENT ON COLUMN pay_batches.meta   IS 'ค่าตั้งที่ใช้ตอนปิด · ไฟล์ K BIZ {name, eff, rows:[{emp_id, nick, acc, name, amount}]} · ผลเทียบไฟล์ · คนที่ปิดด้วยยอดที่โอนจริง';

-- 2) สลิปแช่แข็งต่อคน·งวด·รุ่น
CREATE TABLE IF NOT EXISTS pay_slips (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE RESTRICT,
  period      text NOT NULL CONSTRAINT pay_slips_period_chk CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  ver         integer NOT NULL CHECK (ver >= 1),
  kind        text NOT NULL CHECK (kind IN ('close', 'reopen')),
  batch_id    bigint NOT NULL REFERENCES pay_batches (id) ON DELETE RESTRICT,
  cycle       text NOT NULL CHECK (cycle IN ('store', 'office')),
  branch      text NOT NULL DEFAULT '',
  src         text NOT NULL DEFAULT '' CHECK (src IN ('', 'calc', 'paid', 'file')),
  net         numeric(12,2) NOT NULL DEFAULT 0,
  base        numeric(12,2) NOT NULL DEFAULT 0,
  add_sum     numeric(12,2) NOT NULL DEFAULT 0,
  dedu_sum    numeric(12,2) NOT NULL DEFAULT 0,
  paid        numeric(12,2),
  carry       jsonb NOT NULL DEFAULT '{}'::jsonb,
  pay         jsonb,
  slip        jsonb,
  note        text NOT NULL DEFAULT '',
  sha         text NOT NULL DEFAULT '',
  app_ver     text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pay_slips_ver_uq UNIQUE (employee_id, period, ver),
  CONSTRAINT pay_slips_body_chk CHECK (kind <> 'close' OR (pay IS NOT NULL AND slip IS NOT NULL))
);
ALTER TABLE pay_slips ADD COLUMN IF NOT EXISTS note text NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS pay_slips_period_idx ON pay_slips (period);
CREATE INDEX IF NOT EXISTS pay_slips_batch_idx ON pay_slips (batch_id);

COMMENT ON COLUMN pay_slips.kind   IS 'close = ปิดแล้ว · reopen = เปิดงวดใหม่ (ไม่มีเนื้อสลิป) — สถานะ = แถวรุ่นสูงสุดของคน·งวด';
COMMENT ON COLUMN pay_slips.branch IS 'สาขา ณ วันปิด';
COMMENT ON COLUMN pay_slips.src    IS 'calc = ปิดด้วยยอดที่ระบบคิด · paid = ปิดด้วยยอดที่โอนจริง (มีบรรทัดปรับในสลิปงวดนี้เอง) · file = ปิดย้อนหลังจากไฟล์ที่จ่ายจริง';
COMMENT ON COLUMN pay_slips.paid   IS 'ยอดในไฟล์โอน K BIZ / ไฟล์ที่จ่ายจริง · NULL = ไม่มีหลักฐานนอกระบบ (เงินสด ฯลฯ)';
COMMENT ON COLUMN pay_slips.carry  IS 'ยอดยกไปงวดถัดไป (เงินประกัน/MOU/เงินยืม/สำรองฯ สะสม · id สัญญา)';
COMMENT ON COLUMN pay_slips.pay    IS 'ผลคิดเงินแบบแช่แข็ง — ทุกจออ่านแทนการคิดใหม่';
COMMENT ON COLUMN pay_slips.slip   IS 'ข้อความทุกบรรทัดของสลิป + ตารางเข้างาน ณ วันปิด';
COMMENT ON COLUMN pay_slips.note   IS 'เหตุผลรายคน เช่น ปิดตามยอดที่โอนจริง (ไฟล์ X · ระบบ Y)';
COMMENT ON COLUMN pay_slips.sha    IS 'SHA-256 ของ pay+slip ตอนปิด (ตรวจว่าไม่ถูกแก้นอกแอป)';

-- 3) ห้ามแก้/ลบ/ล้างตาราง ทั้งจากแอปและ SQL Editor
--    จำเป็นจริง (ปรึกษาก่อน) = ใน transaction เดียว: BEGIN; SET LOCAL jj.pay_admin = 'on'; …; COMMIT;
CREATE OR REPLACE FUNCTION pay_ro_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
  IF coalesce(current_setting('jj.pay_admin', true), '') = 'on' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  RAISE EXCEPTION 'JJ_CLOSED: % เป็นฉบับปิดงวด แก้/ลบไม่ได้ — เปิดงวดใหม่ด้วยปุ่มในแอป (เจ้าของ/แอดมิน)', TG_TABLE_NAME;
END $$;

DROP TRIGGER IF EXISTS pay_slips_ro ON pay_slips;
CREATE TRIGGER pay_slips_ro BEFORE UPDATE OR DELETE ON pay_slips FOR EACH ROW EXECUTE FUNCTION pay_ro_guard();
DROP TRIGGER IF EXISTS pay_slips_ro_t ON pay_slips;
CREATE TRIGGER pay_slips_ro_t BEFORE TRUNCATE ON pay_slips FOR EACH STATEMENT EXECUTE FUNCTION pay_ro_guard();
DROP TRIGGER IF EXISTS pay_batches_ro ON pay_batches;
CREATE TRIGGER pay_batches_ro BEFORE UPDATE OR DELETE ON pay_batches FOR EACH ROW EXECUTE FUNCTION pay_ro_guard();
DROP TRIGGER IF EXISTS pay_batches_ro_t ON pay_batches;
CREATE TRIGGER pay_batches_ro_t BEFORE TRUNCATE ON pay_batches FOR EACH STATEMENT EXECUTE FUNCTION pay_ro_guard();

-- 4) RLS: อ่าน + เพิ่ม ได้ · แก้/ลบ ไม่มี policy (= ทำไม่ได้)
ALTER TABLE pay_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE pay_slips ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pay_batches' AND policyname = 'pay_batches_read') THEN
    CREATE POLICY pay_batches_read ON pay_batches FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pay_batches' AND policyname = 'pay_batches_add') THEN
    CREATE POLICY pay_batches_add ON pay_batches FOR INSERT WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pay_slips' AND policyname = 'pay_slips_read') THEN
    CREATE POLICY pay_slips_read ON pay_slips FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pay_slips' AND policyname = 'pay_slips_add') THEN
    CREATE POLICY pay_slips_add ON pay_slips FOR INSERT WITH CHECK (true);
  END IF;
END
$$;

-- 5) สิทธิ์ Data API (ตารางใหม่ไม่ได้สิทธิ์อัตโนมัติ — Supabase เลิกเปิดให้เอง 2026-10-30) · anon/authenticated ให้แค่อ่าน + เพิ่ม (แก้/ลบไม่ได้)
--    service_role ได้ทั้งหมด (trigger ข้อ 3 ยังกันแก้/ลบ) · identity ไม่ต้องให้สิทธิ์ sequence
--    REVOKE ครบทุกสิทธิ์ที่เหลือ (UPDATE/DELETE/TRUNCATE/REFERENCES/TRIGGER) — โปรเจกต์ที่ยังมี default privileges แบบเดิม (GRANT ALL ให้ anon อัตโนมัติ) จะได้แค่อ่าน + เพิ่มเหมือนกัน
GRANT SELECT, INSERT ON TABLE pay_batches TO anon, authenticated;
GRANT SELECT, INSERT ON TABLE pay_slips TO anon, authenticated;
REVOKE UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON pay_batches, pay_slips FROM anon, authenticated;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    GRANT ALL ON TABLE pay_batches, pay_slips TO service_role;
  END IF;
END
$$;

-- 6) realtime (แอปฟังในช่องแยก jjmk-close — ห้ามใส่ jjmk-live)
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE pay_batches;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE pay_slips;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
END
$$;

