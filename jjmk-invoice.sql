-- ---------- ตั้งเลขบิลต่อจากระบบเดิม (มีแถวอยู่แล้วจะไม่ทับ) ----------
-- JJRD ใช้ถึง 1005 (ใบต่อไป 1006) · JJLP เริ่ม 1001
insert into public.inv_counters (prefix, last_no) values ('JJRD', 1005), ('JJLP', 1000)
  on conflict (prefix) do nothing;

-- ---------- RPC ออกเลขบิลแบบ atomic (กันเลขซ้ำ) ----------
-- p_start = เลขบิลใบแรกที่จะออก ถ้ายังไม่มีแถว counter ของสาขานั้น
create or replace function public.inv_next_bill_no(p_prefix text, p_start integer default 1)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_no integer;
begin
  insert into public.inv_counters as c (prefix, last_no)
  values (p_prefix, greatest(p_start, 1))
  on conflict (prefix) do update set last_no = c.last_no + 1
  returning last_no into v_no;
  return p_prefix || lpad(v_no::text, 4, '0');
end;
$$;

