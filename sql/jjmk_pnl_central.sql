--   ออฟฟิศ/ส่วนกลาง = ที่ลงรายจ่ายกลาง (ค่าแอด เน็ต เงินเดือน) ไม่ใช่สาขาขายของ
--   แอพใช้ธงนี้: ซ่อนหน้ารายรับ/สต๊อก/ครัวกลาง ตอนเลือกส่วนกลาง ·
--   ไม่เอาไปเทียบในตารางเทียบสาขา แต่ค่าใช้จ่ายยังรวมในกำไรบริษัท (ทุกสาขา) ตามเดิม
-- ============================================================
alter table pnl_branches add column if not exists is_central boolean not null default false;

-- ตั้งให้ "ออฟฟิศ" ที่สร้างไว้แล้วเป็นส่วนกลางอัตโนมัติ (แก้ทีหลังได้ในหน้าตั้งค่า)
update pnl_branches set is_central = true where name like '%ออฟฟิศ%' and is_central = false;

-- ---------- ตรวจผล ----------
select code as รหัส, name as ชื่อ, is_central as ส่วนกลาง from pnl_branches order by sort, code;
-- คาด: แถว "ออฟฟิศ" ขึ้น ส่วนกลาง = true · สาขาอื่น false
