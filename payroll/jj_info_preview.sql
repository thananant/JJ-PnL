  e.full_name                                AS "ชื่อเต็ม(ระบบ)",
  e.branch                                   AS "สาขา",
  e.code                                     AS "รหัส",
  i.birth                                    AS "วันเกิด",
  i.phone                                    AS "เบอร์",
  i.bank || CASE WHEN i.acc <> '' THEN ' ' || i.acc ELSE '' END AS "บัญชี"
FROM i
