-- 1) รายการเบิกคืน (รายครั้ง)
CREATE TABLE IF NOT EXISTS deposit_payouts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees (id) ON DELETE RESTRICT,
  period      text NOT NULL CONSTRAINT deposit_payouts_period_chk CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  amount      numeric NOT NULL CONSTRAINT deposit_payouts_amount_chk CHECK (amount > 0),
  pay_date    date NOT NULL DEFAULT CURRENT_DATE,
  via         text NOT NULL DEFAULT 'cash' CONSTRAINT deposit_payouts_via_chk CHECK (via IN ('cash','transfer')),
  note        text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE  deposit_payouts        IS 'เบิกเงินประกันคืนระหว่างทำงาน (นอกสลิป) — ลดยอดสะสมหลังงวดนั้น งวดถัดไปหักต่อจนครบเป้า';
COMMENT ON COLUMN deposit_payouts.period IS 'งวดที่ตัดยอด YYYY-MM (แอปบันทึกได้เฉพาะงวดที่ยังไม่ถึงวันจ่าย)';
COMMENT ON COLUMN deposit_payouts.amount IS 'ยอดที่เบิกคืน (บาท) — เฉพาะส่วนที่อยู่ในระบบ ไม่รวมยอดที่เก็บก่อนเข้าระบบ';
COMMENT ON COLUMN deposit_payouts.via    IS 'cash = เงินสด · transfer = โอน (นอกสลิปทั้งคู่)';

CREATE INDEX IF NOT EXISTS deposit_payouts_emp_idx ON deposit_payouts (employee_id, period);

-- 1.1) รันซ้ำบนตารางที่สร้างไว้ก่อนแล้ว: เติม CHECK ที่ยังไม่มี · CHECK งวดแบบเก่า (ยอม 2026-13/2026-00) → เปลี่ยนเป็นเดือน 01–12
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'deposit_payouts_period_chk'
             AND conrelid = 'public.deposit_payouts'::regclass AND pg_get_constraintdef(oid) NOT LIKE '%0[1-9]|1[0-2]%') THEN
    ALTER TABLE deposit_payouts DROP CONSTRAINT deposit_payouts_period_chk;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'deposit_payouts_period_chk') THEN
    ALTER TABLE deposit_payouts ADD CONSTRAINT deposit_payouts_period_chk CHECK (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'deposit_payouts_amount_chk') THEN
    ALTER TABLE deposit_payouts ADD CONSTRAINT deposit_payouts_amount_chk CHECK (amount > 0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'deposit_payouts_via_chk') THEN
    ALTER TABLE deposit_payouts ADD CONSTRAINT deposit_payouts_via_chk CHECK (via IN ('cash','transfer'));
  END IF;
END
$$;

-- 2) RLS แบบเดียวกับตารางอื่นของระบบ
ALTER TABLE deposit_payouts ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'deposit_payouts' AND policyname = 'deposit_payouts_all') THEN
    CREATE POLICY deposit_payouts_all ON deposit_payouts FOR ALL USING (true) WITH CHECK (true);
  END IF;
END
$$;

-- 2.1) สิทธิ์อ่าน/เขียนของแอป (โปรเจกต์นี้ตารางใหม่ไม่ได้สิทธิ์อัตโนมัติ)
--      ไม่ใส่ = แอปขึ้น "ไม่มีสิทธิ์อ่าน deposit_payouts — รัน GRANT" และบล็อกสลิป/Excel/K BIZ ทั้งแอปเงินเดือน · รันซ้ำได้
GRANT SELECT, INSERT, UPDATE, DELETE ON deposit_payouts TO anon, authenticated;
GRANT ALL ON deposit_payouts TO service_role;

-- 3) เปิด realtime (แอปฟังในช่องแยก jjmk-depo — ไม่ใช่ jjmk-live)
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE deposit_payouts;
  EXCEPTION WHEN duplicate_object THEN NULL;
  END;
END
$$;

-- ===== JJ-GRANTS: สิทธิ์ Data API ของตารางในไฟล์นี้ (2026-10-21) =====
-- ตั้งแต่ 2026-10-30 Supabase ไม่เปิดสิทธิ์ให้ตารางใหม่เองแล้ว — ไม่มีบล็อกนี้ แอป (คีย์สาธารณะ) จะเจอ permission denied
-- สิทธิ์เท่ากับที่แอปใช้อยู่จริงก่อนหน้านี้ · ตาราง/วิวที่ไม่มีจะข้าม · รันซ้ำได้ · RLS ยังคุมแถวเหมือนเดิม
do $jjg$
declare t text; s text; tb text[] := array['deposit_payouts']::text[]; tr text[] := array[]::text[]; vw text[] := array[]::text[];
begin
  foreach t in array tb || tr loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select, insert, update%s on table public.%I to anon, authenticated',
                   case when t = any(tr) then '' else ', delete' end, t);
    execute format('grant all on table public.%I to service_role', t);
    for s in select c.relname from pg_class c join pg_depend d on d.objid = c.oid and d.deptype in ('a','i')
             where c.relkind = 'S' and d.refobjid = ('public.'||quote_ident(t))::regclass loop
      execute format('grant usage, select on sequence public.%I to anon, authenticated, service_role', s);
    end loop;
  end loop;
  foreach t in array vw loop
    if to_regclass('public.'||quote_ident(t)) is null then continue; end if;
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $jjg$;

-- 4) ตรวจหลังรัน (อ่านอย่างเดียว) — ควรได้ 1 แถว: ตาราง · มี RLS · อยู่ใน realtime · แอปเขียนได้ (anon_write)
SELECT c.relname AS table_name, c.relrowsecurity AS rls_on,
       EXISTS (SELECT 1 FROM pg_publication_tables t WHERE t.pubname = 'supabase_realtime' AND t.tablename = 'deposit_payouts') AS realtime_on,
       has_table_privilege('anon', 'public.deposit_payouts', 'SELECT,INSERT,UPDATE,DELETE') AS anon_write
FROM pg_class c WHERE c.relname = 'deposit_payouts';
