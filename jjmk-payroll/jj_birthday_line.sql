-- jj_birthday_line.sql — แจ้งวันเกิดพนักงานเข้ากลุ่มไลน์ (JJ-Payroll · เจ้าของสั่ง 2026-10-15)
-- เวอร์ชัน 2026-10-15.1 · กด Ctrl+A แล้ว Run ทั้งไฟล์ · รันซ้ำได้ ไม่ลบข้อมูลเดิม
--
-- ส่งอะไร
--   ① วันที่ 1 ของทุกเดือน (ตั้งต้น 09:00 เวลาไทย) → เดือนนี้ใครเกิดบ้าง · กี่คน · วันไหน (แยกนับตามสาขา)
--   ② (เลือกเปิดได้ · ตั้งต้นปิด) เช้าวันเกิด → "วันนี้วันเกิด …" เฉพาะวันที่มีคนเกิด
--   นับเฉพาะพนักงานที่ยังทำงานอยู่ (employees.active) ที่กรอกวันเกิดแล้ว · คนเกิด 29 ก.พ. ปีปกติ = ฉลอง 28 ก.พ.
--
-- ส่งทางไหน
--   ฐานข้อมูลส่งเอง: pg_cron เรียก payroll_line_tick() ทุก 10 นาที → Edge Function 'line-order'
--   (บอทไลน์ตัวเดียวกับรายงานเข้างาน/นับสต๊อก/ครัวกลาง · body = {to,text}) — ไม่ต้องเปิดแอปค้างไว้
--   เลือกกลุ่ม (กลุ่ม daily report) + เวลาส่ง ที่แอปเงินเดือน → ⚙️ ตั้งค่า → การ์ด "🎂 แจ้งวันเกิดเข้ากลุ่มไลน์"
--   (เก็บที่ payroll_settings.bday_line — ยังไม่เลือกกลุ่ม = ไม่ส่งอะไรเลย)
-- ============================================================

create extension if not exists pg_cron;
create extension if not exists pg_net;

-- ---------- ค่าตั้ง (แอปเขียน) ----------
-- {"group":"C…","month":true,"month_at":"09:00","day":false,"day_at":"09:00","since":"<ISO>"}
alter table public.payroll_settings add column if not exists bday_line jsonb not null default '{}'::jsonb;

-- ---------- ประวัติการส่ง + ตัวกันส่งซ้ำ ----------
-- 1 แถว = 1 ข้อความ (ชนิด × เดือน/วัน) · ส่งสำเร็จแล้วไม่ส่งซ้ำอีก · ส่งไม่สำเร็จลองใหม่ได้รวม 3 ครั้ง
-- คีย์สาธารณะของแอปอ่านได้อย่างเดียว — เขียนได้แค่ payroll_line_tick (security definer)
create table if not exists public.payroll_line_log (
  id          bigint generated by default as identity primary key,
  kind        text        not null,          -- 'bday_month' | 'bday_day'
  period_key  text        not null,          -- '2026-10' (รายเดือน) | '2026-10-15' (เช้าวันเกิด)
  group_id    text,
  tries       int         not null default 0,
  ok          boolean,                        -- null = ส่งแล้วยังไม่รู้ผล · true = ไลน์รับแล้ว · false = ส่งไม่สำเร็จ
  req_id      bigint,                         -- id คำขอของ pg_net (ตามผลในรอบถัดไป)
  detail      text,
  first_at    timestamptz not null default now(),
  sent_at     timestamptz,
  constraint payroll_line_log_once unique (kind, period_key)
);

alter table public.payroll_line_log enable row level security;
drop policy if exists payroll_line_log_read on public.payroll_line_log;
create policy payroll_line_log_read on public.payroll_line_log for select using (true);
revoke insert, update, delete, truncate on public.payroll_line_log from anon, authenticated;
grant select on public.payroll_line_log to anon, authenticated;

