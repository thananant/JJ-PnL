-- เลขบิลรันต่อสาขา (last_no = เลขล่าสุดที่ใช้แล้ว · ใบต่อไป = +1)
create table if not exists public.inv_counters (
  prefix   text primary key,           -- JJRD / JJLP
  last_no  integer not null default 0
);

create table if not exists public.inv_invoices (
  id             bigint generated by default as identity primary key,
  bill_no        text not null unique,              -- เช่น JJRD1006
  branch_prefix  text not null,
  issued_at      timestamptz not null default now(),
  customer_name  text,
  tax_id         text,
  phone          text,
  email          text,
  address        text,
  items          jsonb not null default '[]'::jsonb,
  gross          numeric(12,2) not null default 0,  -- รวมทั้งสิ้น (รวม VAT)
  discount       numeric(12,2) not null default 0,
  net            numeric(12,2) not null default 0,  -- มูลค่าสุทธิก่อน VAT
  vat            numeric(12,2) not null default 0,
  grand_total    numeric(12,2) not null default 0,
  payment_method text,
  status         text not null default 'ออกแล้ว',    -- ออกแล้ว / ยกเลิก
  status_detail  text,
  nas_path       text,                               -- ที่เก็บไฟล์ใน NAS เช่น 2026-09/JJRD1006.pdf
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists inv_invoices_branch_idx on public.inv_invoices (branch_prefix, issued_at desc);
create index if not exists inv_invoices_status_idx on public.inv_invoices (status);

