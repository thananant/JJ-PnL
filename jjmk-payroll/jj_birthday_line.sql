-- ---------- ตัวช่วยอ่านค่าแบบไม่ล้ม (ค่าตั้งเขียนได้จากแอป — ค่าเพี้ยนต้องไม่ทำให้ตัวส่งล้มทั้งงาน) ----------
create or replace function public.payroll_try_jsonb(p text)
returns jsonb
language plpgsql
immutable
as $$
begin
  return p::jsonb;
exception when others then
  return null;
end
$$;

create or replace function public.payroll_try_time(p text, p_def time)
returns time
language plpgsql
immutable
as $$
begin
  if p ~ '^[0-9]{1,2}:[0-9]{2}$' and split_part(p, ':', 1)::int <= 23 and split_part(p, ':', 2)::int <= 59 then
    return p::time;
  end if;
  return p_def;
exception when others then
  return p_def;
end
$$;

create or replace function public.payroll_try_ts(p text)
returns timestamptz
language plpgsql
stable
as $$
begin
  if p is null or p !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then return null; end if;
  return p::timestamptz;
exception when others then
  return null;
end
$$;

-- ---------- วันฉลองวันเกิดในปีที่กำหนด (เกิด 29 ก.พ. + ปีที่ไม่มี 29 ก.พ. = 28 ก.พ.) ----------
create or replace function public.payroll_bday_in(p_birth date, p_year int)
returns date
language sql
immutable
as $$
  select case
           when extract(month from p_birth) = 2 and extract(day from p_birth) = 29
                and not ((p_year % 4 = 0 and p_year % 100 <> 0) or p_year % 400 = 0)
             then make_date(p_year, 2, 28)
           else make_date(p_year, extract(month from p_birth)::int, extract(day from p_birth)::int)
         end;
$$;

-- ---------- ชื่อสาขา (ต้องตรงกับ BR ในแอป / BRT ใน worker.js) ----------
create or replace function public.payroll_br_th(p text)
returns text
language sql
immutable
as $$
  select case btrim(coalesce(p, ''))
           when 'JJLP' then 'ลาดพร้าว' when 'JJRD' then 'รัชดา'
           when 'JJCK' then 'ครัวกลาง' when 'OFFICE' then 'ออฟฟิศ'
           when '' then null
           else btrim(p) end;
$$;

create or replace function public.payroll_br_ord(p text)
returns int
language sql
immutable
as $$
  select case btrim(coalesce(p, '')) when 'JJLP' then 1 when 'JJRD' then 2 when 'JJCK' then 3 when 'OFFICE' then 4
                                     when '' then 9 else 5 end;
$$;

drop function if exists public.payroll_bday_line(text, text, text, text);

-- ---------- 1 บรรทัดต่อคน: "• นุ่น · รัชดา" ----------
-- ใช้ชื่อเล่นแบบเดียวกับรายงานเข้างานในกลุ่ม · ชื่อจริงต่อท้ายเฉพาะเมื่อชื่อเล่นซ้ำกันในข้อความเดียวกัน (p_dup) ให้แยกคนออก
-- ไม่มีชื่อเล่น = ใช้ชื่อจริง → รหัสเครื่องสแกน
create or replace function public.payroll_bday_line(p_nick text, p_full text, p_code text, p_branch text, p_dup boolean)
returns text
language sql
immutable
as $$
  select '• ' || left(coalesce(nullif(btrim(p_nick), ''), nullif(btrim(p_full), ''), nullif(btrim(p_code), ''), 'ไม่ทราบชื่อ'), 40)
      || case when p_dup and nullif(btrim(p_nick), '') is not null and nullif(btrim(p_full), '') is not null
                   and btrim(p_full) <> btrim(p_nick)
              then ' (' || left(btrim(p_full), 60) || ')' else '' end
      || coalesce(' · ' || public.payroll_br_th(p_branch), '');
$$;

-- ---------- ① ข้อความรายเดือน: ใครเกิดเดือนนี้ กี่คน วันไหน ----------
-- p_day = วันไหนก็ได้ในเดือนที่ต้องการ (ว่าง = เดือนนี้ตามเวลาไทย)
-- แอปเรียกฟังก์ชันนี้ดูตัวอย่าง/กดส่งเอง (อ่านอย่างเดียว ไม่เขียนอะไร)
create or replace function public.payroll_bday_month_text(p_day date default null)
returns text
language plpgsql
stable
set search_path = public, pg_temp
as $$
declare
  c_max  constant int    := 60;     -- รายชื่อยาวสุดกี่บรรทัด
  c_len  constant int    := 4300;   -- ยาวสุดกี่ตัวอักษร (ไลน์รับข้อความละ 5,000 — เผื่อบรรทัดท้าย)
  c_mon  constant text[] := array['มกราคม','กุมภาพันธ์','มีนาคม','เมษายน','พฤษภาคม','มิถุนายน',
                                  'กรกฎาคม','สิงหาคม','กันยายน','ตุลาคม','พฤศจิกายน','ธันวาคม'];
  c_mab  constant text[] := array['ม.ค.','ก.พ.','มี.ค.','เม.ย.','พ.ค.','มิ.ย.','ก.ค.','ส.ค.','ก.ย.','ต.ค.','พ.ย.','ธ.ค.'];
  c_dow  constant text[] := array['อา.','จ.','อ.','พ.','พฤ.','ศ.','ส.'];
  c_bar  constant text   := '━━━━━━━━━━━━';
  v_d    date := coalesce(p_day, (now() at time zone 'Asia/Bangkok')::date);
  v_y    int  := extract(year from v_d)::int;
  v_m    int  := extract(month from v_d)::int;
  v_n    int;
  v_miss int;
  v_br   text;
  v_txt  text;
  v_last date;
  v_add  text;
  i      int := 0;
  r      record;
begin
  select count(*)::int into v_n
    from employees e
   where coalesce(e.active, false) and e.birth_date is not null
     and extract(month from e.birth_date) = v_m;

  select count(*)::int into v_miss
    from employees e
   where coalesce(e.active, false) and e.birth_date is null;

  v_txt := '🎂 วันเกิดพนักงาน เดือน' || c_mon[v_m] || ' ' || (v_y + 543)::text;

  if coalesce(v_n, 0) = 0 then
    v_txt := v_txt || chr(10) || 'ไม่มีพนักงานที่เกิดเดือน' || c_mon[v_m] || ' 🎈';
  else
    select string_agg(coalesce(public.payroll_br_th(q.b), 'ไม่ระบุสาขา') || ' ' || q.n, ' · ' order by q.o, q.b)
      into v_br
      from (select btrim(coalesce(e.branch, '')) as b, public.payroll_br_ord(e.branch) as o, count(*)::int as n
              from employees e
             where coalesce(e.active, false) and e.birth_date is not null
               and extract(month from e.birth_date) = v_m
             group by 1, 2) q;
    v_txt := v_txt || chr(10) || 'รวม ' || v_n || ' คน' || coalesce(' · ' || v_br, '') || chr(10) || c_bar;

    for r in
      select public.payroll_bday_in(e.birth_date, v_y) as cd,
             (extract(month from e.birth_date) = 2 and extract(day from e.birth_date) = 29) as feb29,
             e.nick, e.full_name, e.code, e.branch,
             count(*) over (partition by coalesce(lower(nullif(btrim(e.nick), '')), '#' || e.id::text)) > 1 as dup
        from employees e
       where coalesce(e.active, false) and e.birth_date is not null
         and extract(month from e.birth_date) = v_m
       order by 1, public.payroll_br_ord(e.branch), coalesce(nullif(btrim(e.nick), ''), e.full_name, e.code), e.id
    loop
      v_add := case when v_last is distinct from r.cd
                    then chr(10) || '📅 ' || extract(day from r.cd)::int || ' ' || c_mab[v_m]
                         || ' (' || c_dow[extract(dow from r.cd)::int + 1] || ')' else '' end
            || chr(10) || public.payroll_bday_line(r.nick, r.full_name, r.code, r.branch, r.dup)
            || case when r.feb29 and extract(day from r.cd) = 28 then ' (เกิด 29 ก.พ.)' else '' end;
      exit when i >= c_max or char_length(v_txt) + char_length(v_add) > c_len;
      v_txt := v_txt || v_add;
      v_last := r.cd;
      i := i + 1;
    end loop;
    if i < v_n then
      v_txt := v_txt || chr(10) || '…และอีก ' || (v_n - i) || ' คน (ดูครบในแอปเงินเดือน)';
    end if;
  end if;

  if coalesce(v_miss, 0) > 0 then
    v_txt := v_txt || chr(10) || c_bar || chr(10)
          || '📝 ยังไม่ได้กรอกวันเกิด ' || v_miss || ' คน — เติมได้ที่แอปเงินเดือน › ข้อมูลพนักงาน › ข้อมูลส่วนตัว';
  end if;
  return v_txt;
end
$$;

-- ---------- ② ข้อความเช้าวันเกิด (ไม่มีใครเกิดวันนั้น = คืน null = ไม่ส่ง) ----------
create or replace function public.payroll_bday_day_text(p_day date default null)
returns text
language plpgsql
stable
set search_path = public, pg_temp
as $$
declare
  c_mab  constant text[] := array['ม.ค.','ก.พ.','มี.ค.','เม.ย.','พ.ค.','มิ.ย.','ก.ค.','ส.ค.','ก.ย.','ต.ค.','พ.ย.','ธ.ค.'];
  c_dowf constant text[] := array['อาทิตย์','จันทร์','อังคาร','พุธ','พฤหัสบดี','ศุกร์','เสาร์'];
  v_d    date := coalesce(p_day, (now() at time zone 'Asia/Bangkok')::date);
  v_y    int  := extract(year from v_d)::int;
  v_n    int  := 0;
  v_tot  int  := 0;
  v_add  text;
  v_body text := '';
  r      record;
begin
  for r in
    select e.nick, e.full_name, e.code, e.branch,
           count(*) over (partition by coalesce(lower(nullif(btrim(e.nick), '')), '#' || e.id::text)) > 1 as dup
      from employees e
     where coalesce(e.active, false) and e.birth_date is not null
       and extract(month from e.birth_date) = extract(month from v_d)
       and public.payroll_bday_in(e.birth_date, v_y) = v_d
     order by public.payroll_br_ord(e.branch), coalesce(nullif(btrim(e.nick), ''), e.full_name, e.code), e.id
  loop
    v_tot := v_tot + 1;
    v_add := chr(10) || public.payroll_bday_line(r.nick, r.full_name, r.code, r.branch, r.dup);
    if v_n < 40 and char_length(v_body) + char_length(v_add) <= 4300 then
      v_body := v_body || v_add;
      v_n := v_n + 1;
    end if;
  end loop;
  if v_tot = 0 then return null; end if;
  if v_tot > v_n then v_body := v_body || chr(10) || '…และอีก ' || (v_tot - v_n) || ' คน'; end if;
  return '🎂 วันนี้วันเกิดพนักงาน' || case when v_tot > 1 then ' ' || v_tot || ' คน' else '' end
      || ' · วัน' || c_dowf[extract(dow from v_d)::int + 1] || ' ' || extract(day from v_d)::int
      || ' ' || c_mab[extract(month from v_d)::int] || ' ' || (v_y + 543)::text
      || v_body || chr(10) || 'ร่วมอวยพรวันเกิดกันนะ 🎉';
end
$$;

grant execute on function public.payroll_bday_month_text(date) to anon, authenticated;
grant execute on function public.payroll_bday_day_text(date)   to anon, authenticated;

-- ---------- งานที่ถึงเวลาส่งแล้วแต่ยังไม่ได้ส่ง ----------
-- · ไม่มีกลุ่ม/ไอดีกลุ่มผิดรูปแบบ = ไม่ส่ง
-- · since = เวลาที่กดบันทึกครั้งแรกในแอป — เพิ่งตั้งค่ากลางเดือน จะไม่ย้อนส่งของวันที่ 1 ให้ (กด 📤 ส่งเดี๋ยวนี้ในแอปแทน)
-- · รายเดือนส่ง/ลองใหม่ได้ถึงวันที่ 4 (มองย้อนหลัง 3 วัน — cron หยุดไปแล้วกลับมา ส่งตามให้) · เช้าวันเกิดส่งได้เฉพาะวันนั้น
-- · เวลาส่งช้าสุด 23:30 (ตั้งเกินกว่านี้ = 23:30 — cron ทุก 10 นาทีต้องทันก่อนข้ามวัน)
-- · ส่งไม่สำเร็จ ลองใหม่รวม 3 ครั้ง: รายเดือนเว้น 30 แล้ว 60 นาที · เช้าวันเกิดเว้น 10 นาที — เหตุผลครั้งก่อนเก็บไว้จนผลครั้งใหม่มา
-- · วันที่ 1 ที่มีคนเกิด: ส่งรายชื่อทั้งเดือนก่อน แล้ว "วันนี้วันเกิด" ตามในรอบถัดไป
create or replace function public.payroll_line_due(p_now timestamptz default now())
returns table (kind text, period_key text, group_id text, d date, due_at timestamptz)
language sql
stable
set search_path = public, pg_temp
as $$
  with cfg as (
    select coalesce((select ps.bday_line from payroll_settings ps where ps.id = 1), '{}'::jsonb) as v
  ), s as (
    select btrim(coalesce(v->>'group', ''))                                   as gid,
           case lower(coalesce(v->>'month', '')) when 'false' then false else true  end as month_on,
           case lower(coalesce(v->>'day', ''))   when 'true'  then true  else false end as day_on,
           least(public.payroll_try_time(v->>'month_at', time '09:00'), time '23:30') as month_at,
           least(public.payroll_try_time(v->>'day_at',   time '09:00'), time '23:30') as day_at,
           coalesce(public.payroll_try_ts(v->>'since'), p_now - interval '20 hours') as since,
           (p_now at time zone 'Asia/Bangkok')::date                         as today
      from cfg
  ), cand as (
    select 'bday_month'::text as kind, to_char(x.d, 'YYYY-MM') as period_key, x.d::date as d,
           ((x.d::date + s.month_at) at time zone 'Asia/Bangkok') as due_at
      from s, generate_series(s.today - 3, s.today, interval '1 day') as x(d)
     where s.month_on and extract(day from x.d) = 1
    union all
    select 'bday_day'::text, to_char(s.today, 'YYYY-MM-DD'), s.today,
           ((s.today + s.day_at) at time zone 'Asia/Bangkok')
      from s
     where s.day_on
       and exists (select 1 from employees e
                    where coalesce(e.active, false) and e.birth_date is not null
                      and extract(month from e.birth_date) = extract(month from s.today)
                      and public.payroll_bday_in(e.birth_date, extract(year from s.today)::int) = s.today)
  ), ready as (
    select c.* from cand c cross join s
     where s.gid ~ '^[CRU][0-9a-f]{32}$'
       and c.due_at <= p_now
       and c.due_at >= s.since
       and not exists (
         select 1 from payroll_line_log l
          where l.kind = c.kind and l.period_key = c.period_key
            and (l.ok is not false or l.tries >= 3
                 -- ลองใหม่เว้นระยะ: รายเดือน 30 แล้ว 60 นาที (มีเวลา 4 วัน) · เช้าวันเกิดทุก 10 นาที (ต้องทันภายในวันนั้น)
                 or l.sent_at > p_now - case when c.kind = 'bday_day' then interval '10 minutes'
                                             else interval '30 minutes' * l.tries end))
  )
  select r.kind, r.period_key, s.gid, r.d, r.due_at
    from ready r cross join s
   -- วันที่ 1 ที่มีคนเกิด: "วันนี้วันเกิด" รอให้รายชื่อทั้งเดือนออกไปก่อน 1 รอบ (ส่งรอบเดียวกัน pg_net ยิงพร้อมกัน ลำดับในไลน์สลับได้)
   where not (r.kind = 'bday_day' and exists (
           select 1 from ready m where m.kind = 'bday_month' and m.d = r.d)
          or r.kind = 'bday_day' and exists (
           select 1 from payroll_line_log l
            where l.kind = 'bday_month' and l.period_key = to_char(r.d, 'YYYY-MM')
              and l.ok is null and l.sent_at > p_now - interval '9 minutes'))
   order by r.due_at, r.kind;
$$;

-- ---------- ตัวเดินงาน (cron เรียกทุก 10 นาที · p_now มีไว้ทดสอบ — cron เรียกแบบไม่ใส่) ----------
-- ① เก็บผลการส่งรอบก่อน (pg_net ส่งแบบไม่รอคำตอบ — ผลอยู่ใน net._http_response)
--    สำเร็จ = HTTP 2xx และ line-order ไม่ได้ตอบ {"ok":false} · ต่อไม่ติด/หมดเวลา = ไม่สำเร็จ (ลองใหม่)
-- ② ส่งงานที่ถึงเวลา · จองแถวใน payroll_line_log ก่อนยิงเสมอ (สำเร็จ/ยังไม่รู้ผล = ไม่ส่งซ้ำ · ไม่สำเร็จลองได้ 3 ครั้ง)
create or replace function public.payroll_line_tick(p_now timestamptz default now())
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  c_ep   constant text := 'https://aikyxvluaiubdidqxwnd.supabase.co/functions/v1/line-order';
  c_key  constant text := 'sb_publishable_Bn6BMtcjasoPT3RZ_ekyOg_SLWWp-nm';  -- คีย์สาธารณะชุดเดียวกับหน้าแอป
  r       record;
  v_id    bigint;
  v_req   bigint;
  v_txt   text;
  n_sent  int := 0;
  n_fail  int := 0;
  n_check int := 0;
begin
  begin
    update payroll_line_log l
       set ok      = x.good,
           detail  = x.detail,
           sent_at = coalesce(l.sent_at, p_now)
      from (
        select l2.id, g.good,
               case when g.good then null
                    else left(coalesce(nullif(res.error_msg, ''),
                                       'HTTP ' || coalesce(res.status_code::text, '?') || ' ' || coalesce(res.content, '')), 300) end as detail
          from payroll_line_log l2
          join net._http_response res on res.id = l2.req_id
          cross join lateral (
            select case
                     when res.status_code between 200 and 299
                          and coalesce(public.payroll_try_jsonb(res.content)->>'ok', '') <> 'false' then true
                     when res.status_code is null and coalesce(res.error_msg, '') = '' then null
                     else false
                   end as good) g
         where l2.ok is null and l2.req_id is not null
      ) x
     where l.id = x.id and x.good is not null;
    get diagnostics n_check = row_count;
  exception when others then
    n_check := -1;    -- pg_net เวอร์ชันต่าง/ผลหมดอายุ — ไม่ให้ล้มทั้งงาน
  end;

  for r in select * from payroll_line_due(p_now) loop
    begin
      v_txt := case r.kind when 'bday_month' then payroll_bday_month_text(r.d)
                           else payroll_bday_day_text(r.d) end;
      if v_txt is null or btrim(v_txt) = '' then continue; end if;

      v_id := null;
      insert into payroll_line_log (kind, period_key, group_id, tries, sent_at)
      values (r.kind, r.period_key, r.group_id, 1, p_now)
      on conflict (kind, period_key) do update
         set tries    = payroll_line_log.tries + 1,
             ok       = null,
             req_id   = null,
             group_id = excluded.group_id,
             sent_at  = p_now
       where payroll_line_log.ok is false and payroll_line_log.tries < 3
      returning id into v_id;
      if v_id is null then continue; end if;     -- ส่งสำเร็จแล้ว/ลองครบแล้ว

      select net.http_post(
               url     := c_ep,
               body    := jsonb_build_object('to', r.group_id, 'text', left(v_txt, 4900)),
               headers := jsonb_build_object('Content-Type', 'application/json',
                                             'apikey', c_key,
                                             'Authorization', 'Bearer ' || c_key),
               timeout_milliseconds := 20000)
        into v_req;
      update payroll_line_log set req_id = v_req where id = v_id;
      n_sent := n_sent + 1;
    exception when others then
      -- ส่งไม่ออก (เช่น ยังไม่ได้เปิด pg_net) — จดเหตุผลไว้ให้แอปเห็น · นับเป็น 1 ครั้งที่ลอง (ครบ 3 ครั้งหยุดเอง)
      n_fail := n_fail + 1;
      insert into payroll_line_log (kind, period_key, group_id, tries, ok, detail, sent_at)
      values (r.kind, r.period_key, r.group_id, 1, false, left(sqlerrm, 300), p_now)
      on conflict (kind, period_key) do update
         set tries = payroll_line_log.tries + 1, ok = false, req_id = null,
             detail = excluded.detail, group_id = excluded.group_id, sent_at = p_now
       where payroll_line_log.ok is not true;
    end;
  end loop;

  return jsonb_build_object('sent', n_sent, 'failed', n_fail, 'checked', n_check, 'at', p_now);
end
$$;

-- ตัวเดินงานส่งข้อความออกข้างนอก — ให้เฉพาะ cron เรียก (คีย์สาธารณะเรียกไม่ได้)
revoke all on function public.payroll_line_tick(timestamptz) from public, anon, authenticated;
revoke all on function public.payroll_line_due(timestamptz)   from public, anon, authenticated;

-- ---------- ตารางเวลา ----------
do $$
begin
  perform cron.unschedule('payroll-bday-line');
exception when others then
  null;
end
$$;

-- ทุก 10 นาที: เช็คว่าถึงเวลาส่งหรือยัง (เวลาส่งจริงตั้งในแอป · ตั้งต้น 09:00 เวลาไทย)
select cron.schedule('payroll-bday-line', '*/10 * * * *', $cron$ select public.payroll_line_tick(); $cron$);

notify pgrst, 'reload schema';

-- ---------- ตรวจว่าตั้งสำเร็จ ----------
-- ต้องเห็น 1 แถว active = true
select jobname, schedule, active from cron.job where jobname = 'payroll-bday-line';

-- ตัวอย่างข้อความของเดือนนี้
select public.payroll_bday_month_text() as ตัวอย่างข้อความ;
