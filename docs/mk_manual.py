def fig(path,maxw=158,maxh=110,cap=''):
    w,h=PILImage.open(path).size; r=min(maxw*mm/w, maxh*mm/h)
    out=[RLImage(path,width=w*r,height=h*r)]
    if cap: out.append(Paragraph(cap,S['cap']))
    else: out.append(Spacer(1,6))
    return out
def tip(txt,kind='tip'):
    ic='💡' if kind=='tip' else '⚠️'
    bg=CREAM if kind=='tip' else PINK
    t=Table([[Paragraph(f'<b>{ic} '+('เคล็ดลับ' if kind=='tip' else 'ระวัง')+':</b> '+txt,S['b'])]],colWidths=[168*mm])
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,-1),bg),('BOX',(0,0),(-1,-1),0.7,LINE),
        ('LEFTPADDING',(0,0),(-1,-1),10),('RIGHTPADDING',(0,0),(-1,-1),10),('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7)]))
    return [Spacer(1,4),t,Spacer(1,8)]
def steps(items):
    out=[]
    for i,txt in enumerate(items,1):
        out.append(Paragraph(f'<b><font color="#8E1B1B">ขั้นที่ {i}.</font></b> {txt}',S['step']))
    out.append(Spacer(1,6)); return out
def bullets(items):
    return [Paragraph('• '+t,S['bul']) for t in items]+[Spacer(1,4)]

