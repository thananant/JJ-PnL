cand AS (
  SELECT i.row_no AS iid, e.id AS eid,
    min(CASE
      WHEN lower(trim(e.nick)) = lower(i.nick)
           AND lower(trim(coalesce(e.full_name,''))) = lower(i.name) THEN 1
      WHEN lower(trim(e.nick)) = lower(i.nick)
           AND coalesce(e.full_name,'') <> '' AND i.name <> ''
           AND (e.full_name ILIKE '%'||i.name||'%' OR i.name ILIKE '%'||e.full_name||'%') THEN 2
      WHEN lower(trim(e.nick)) = lower(i.nick) THEN 3
      WHEN i.name <> ''
           AND lower(trim(coalesce(e.full_name,''))) = lower(i.name) THEN 4
    END) AS score
  FROM i
  JOIN employees e ON e.active = true AND (
       lower(trim(e.nick)) = lower(i.nick)
    OR (i.name <> '' AND lower(trim(coalesce(e.full_name,''))) = lower(i.name))
  )
  GROUP BY i.row_no, e.id
),
best AS (
  SELECT iid, min(score) AS s FROM cand WHERE score IS NOT NULL GROUP BY iid
),
pick AS (
  SELECT c.iid, b.s, count(*) AS n, min(c.eid) AS eid
  FROM cand c JOIN best b ON b.iid = c.iid AND c.score = b.s
  GROUP BY c.iid, b.s
)
